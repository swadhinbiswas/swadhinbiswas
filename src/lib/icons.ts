export function thesvgIconUrl(name: string): string | null {
  const key = name.toLowerCase().trim();
  const mapped = thesvgIconMap[key];
  if (!mapped) return null;
  if (mapped.includes("/")) {
    const [pathPart, variant] = mapped.split("/", 2);
    return `https://cdn.jsdelivr.net/gh/glincker/thesvg@main/public/icons/${pathPart}/${variant}.svg`;
  }
  return `https://cdn.jsdelivr.net/gh/glincker/thesvg@main/public/icons/${mapped}/default.svg`;
}

export function skillInitials(name: string): string {
  return name
    .replace(/[^a-zA-Z0-9+#.]/g, "")
    .slice(0, 3)
    .toUpperCase();
}

